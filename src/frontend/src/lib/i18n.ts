export const dictionaries = { ru, en };
export function isLocale(value: string): value is Locale {
  return value === "ru" || value === "en";
}
export function errorMessage(error: unknown, t: Dictionary) {
  const code = error instanceof Error ? error.message : "internal";
  return code in t ? t[code as keyof Dictionary] : t.internal;
}
export function money(value: number, lang: Locale) {
  return new Intl.NumberFormat(lang, { style: "currency", currency: "RUB" }).format(value / 100);
}
